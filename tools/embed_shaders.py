"""Embed GLSL source files in a generated C header."""

from __future__ import annotations

import json
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: embed_shaders.py OUTPUT VERTEX_SHADER FRAGMENT_SHADER", file=sys.stderr)
        return 2

    output, vertex_path, fragment_path = map(Path, sys.argv[1:])
    vertex = vertex_path.read_text(encoding="utf-8")
    fragment = fragment_path.read_text(encoding="utf-8")
    generated = """/* Generated by tools/embed_shaders.py. Do not edit. */
#ifndef PI_DRAW3D_GENERATED_SHADERS_H
#define PI_DRAW3D_GENERATED_SHADERS_H

static const char *const DRAW3D_DEFAULT_VERTEX_SOURCE = %s;
static const char *const DRAW3D_DEFAULT_FRAGMENT_SOURCE = %s;

#endif
""" % (json.dumps(vertex), json.dumps(fragment))

    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != generated:
        output.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
