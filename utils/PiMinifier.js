export default class PiMinifier {
  static minify(source, builtins = BUILTINS) {
    try {
      const scanner = new PiScanner(source);
      const tokens = scanner.scanTokens();
      const parser = new PiParser();
      const statements = parser.parse(tokens);
      const context = new PiContext(builtins);
      return {
        success: true,
        code: statements.minify(context),
      };
    } catch (e) {
      let message;
      if (e instanceof PiException) {
        message = `PiException: ${e}`;
      } else if (e instanceof ParseError) {
        message = `ParseError: ${e}`;
      } else {
        message = `Error: ${e.constructor.name}: ${e.message}`;
      }
      return {
        success: false,
        error: message,
      };
    }
  }
}
